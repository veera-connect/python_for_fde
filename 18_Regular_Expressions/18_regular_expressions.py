# Example 14: Writing RegEx Patterns
import re

# Matching a word
txt = 'veera loves python. veera codes daily.'
print(re.findall(r'veera', txt))   # ['veera', 'veera']

# Character classes \d and \w
txt2 = 'veera has 3 cats and 12 books in 2024'
print(re.findall(r'\d+', txt2))    # digits
print(re.findall(r'\w+', txt2))    # word chunks

# Groups, or operator and anchors
txt3 = 'Apple and banana are fruits'
print(re.findall(r'[Aa]pple|[Bb]anana', txt3))
print(bool(re.search(r'^Apple', txt3)))   # starts with Apple
print(bool(re.search(r'fruits$', txt3)))  # ends with fruits

